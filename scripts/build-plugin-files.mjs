#!/usr/bin/env node
// Generates plugin/payload_lens_files.sql -- the wwv_flow_imp.g_varchar2_table
// hex-chunk assignments + create_plugin_file calls for the built JS/CSS assets.
// Run after `npm run build`, before installing/updating the plugin export.
// Mirrors the real Oracle export convention (hex chunks -> varchar2_to_blob),
// confirmed against a genuine app export -- see docs/architecture.md.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const CHUNK_CHARS = 180; // hex chars per literal (<= 4000 byte VARCHAR2 limit, small for readability)

// Fixed wwv_flow_imp.id() literals -- must match plugin/payload_lens_plugin.sql
// exactly (l_plugin_id, file_js, file_css) so re-running this generator keeps
// updating the same rows instead of creating duplicates.
const PLUGIN_ID_LITERAL = 5750252144018392;

const files = [
  {
    path: join(root, 'dist', 'payload-lens.min.js'),
    fileName: 'payload-lens.min.js',
    mimeType: 'application/javascript',
    idLiteral: 9332284537673136,
  },
  {
    path: join(root, 'dist', 'payload-lens.min.css'),
    fileName: 'payload-lens.min.css',
    mimeType: 'text/css',
    idLiteral: 9575590584576612,
  },
];

function toHexChunks(buf, chunkChars) {
  const hex = buf.toString('hex');
  const chunks = [];
  for (let i = 0; i < hex.length; i += chunkChars) {
    chunks.push(hex.slice(i, i + chunkChars));
  }
  return chunks;
}

function sqlQuote(s) {
  return s.replace(/'/g, "''");
}

let out = [];
out.push('prompt --application/create_plugin/payload_lens_files');
out.push('-'.repeat(80));
out.push('-- PayloadLens for Oracle APEX -- generated plugin file payload (DO NOT EDIT)');
out.push(`-- Generated by scripts/build-plugin-files.mjs on ${new Date().toISOString()}`);
out.push('-- Regenerate with: npm run build:plugin-files');
out.push('-'.repeat(80));
out.push('');

for (const file of files) {
  const buf = readFileSync(file.path);
  const chunks = toHexChunks(buf, CHUNK_CHARS);

  out.push(`prompt --creating plugin file: ${file.fileName}`);
  out.push('begin');
  out.push('    wwv_flow_imp.g_varchar2_table := wwv_flow_imp.empty_varchar2_table;');
  chunks.forEach((chunk, idx) => {
    out.push(`    wwv_flow_imp.g_varchar2_table(${idx + 1}) := '${sqlQuote(chunk)}';`);
  });
  out.push('');
  out.push('    wwv_flow_imp.create_plugin_file(');
  out.push(`        p_id            => wwv_flow_imp.id(${file.idLiteral}),`);
  out.push(`        p_plugin_id     => wwv_flow_imp.id(${PLUGIN_ID_LITERAL}),`);
  out.push(`        p_file_name     => '${sqlQuote(file.fileName)}',`);
  out.push(`        p_mime_type     => '${sqlQuote(file.mimeType)}',`);
  out.push(`        p_file_charset  => 'utf-8',`);
  out.push('        p_file_content  => wwv_flow_imp.varchar2_to_blob(wwv_flow_imp.g_varchar2_table));');
  out.push('end;');
  out.push('/');
  out.push('');
}

const outPath = join(root, 'plugin', 'payload_lens_files.sql');
writeFileSync(outPath, out.join('\n') + '\n', 'utf8');
console.log(`Wrote ${outPath} (${files.length} files, ${out.length} lines)`);
